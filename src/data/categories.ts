// Helper to get all services flattened
export const ALL_SERVICES: ServiceItem[] = CATEGORIES_DATA.flatMap(c => c.services);

export function getCategoryBySlug(slug: string): Category | undefined {
  return CATEGORIES_DATA.find(c => c.slug === slug);
}

export function getServiceBySlug(slug: string): { service: ServiceItem; category: Category } | undefined {
  for (const category of CATEGORIES_DATA) {
    const service = category.services.find(s => s.slug === slug);
    if (service) {
      return { service, category };
    }
  }
  return undefined;
}
